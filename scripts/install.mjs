#!/usr/bin/env node
// Links Agent Skills, hooks, and generated rules into the locations each
// harness discovers. See docs/INSTALL.md for the sources file format.
import { spawnSync } from 'node:child_process';
import {
  existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, readlinkSync,
  realpathSync, renameSync, rmSync, statSync, symlinkSync, unlinkSync, writeFileSync,
} from 'node:fs';
import { homedir } from 'node:os';
import { dirname, isAbsolute, join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const repository = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const RULES_HEADER = '<!-- Generated by the skills installer (scripts/install.sh).';
const COMMIT = /^[0-9a-f]{40}$/;
const NAME = /^[a-z0-9][a-z0-9._-]*$/;

const usage = `Usage: scripts/install.sh [--claude] [--codex] [--agents] [options]

Without a target flag, installs every target.
  --claude               Skills, hooks, status line script, and CLAUDE.md for Claude Code.
  --codex                Rules, lint hook, and shared skills for Codex.
  --agents               Shared skills and rules for Codex, OpenCode, and Gemini CLI.

Options:
  --sources FILE         JSON list of skill sources (default: this repository only).
  --rules-overlay FILE   Markdown appended to rules/AGENTS.md in the generated rules.
  --prune-root DIR       Also remove links that point into DIR (repeatable). Use it
                         once after moving or renaming a previous source.
  --dry-run              Print what would change without changing anything.
  -h, --help             Show this help.

Links into ~/.local/bin/agent-scratch for every target.`;

export function parseArgs(argv) {
  const options = { claude: false, codex: false, agents: false, explicitCodex: false, sources: null, overlay: null, pruneRoots: [], dryRun: false };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    const value = () => {
      if (i + 1 >= argv.length) throw new UsageError(`${arg} needs a value`);
      return argv[++i];
    };
    switch (arg) {
      case '--claude': options.claude = true; break;
      case '--codex': options.codex = true; options.explicitCodex = true; break;
      case '--agents': options.agents = true; break;
      case '--sources': options.sources = value(); break;
      case '--rules-overlay': options.overlay = value(); break;
      case '--prune-root': options.pruneRoots.push(value()); break;
      case '--dry-run': options.dryRun = true; break;
      case '-h': case '--help': options.help = true; break;
      default: throw new UsageError(`Unknown option: ${arg}`);
    }
  }
  if (!options.claude && !options.codex && !options.agents) {
    options.claude = options.codex = options.agents = true;
  }
  return options;
}

class UsageError extends Error {}

function expandHome(path, home) {
  if (path === '~') return home;
  if (path.startsWith('~/')) return join(home, path.slice(2));
  return path;
}

function realOrSelf(path) {
  try { return realpathSync(path); } catch { return resolve(path); }
}

function within(path, root) {
  return path === root || path.startsWith(root.endsWith(sep) ? root : root + sep);
}

function skillNames(directory) {
  return readdirSync(directory, { withFileTypes: true })
    .filter((entry) => !entry.name.startsWith('.') && (entry.isDirectory() || entry.isSymbolicLink()))
    .filter((entry) => existsSync(join(directory, entry.name, 'SKILL.md')))
    .map((entry) => entry.name)
    .sort();
}

function checkoutGit(entry, cacheRoot, log) {
  const spec = entry.git;
  if (typeof spec !== 'string' || !spec) throw new Error('A git source needs "git": "owner/repo" or a URL');
  if (!COMMIT.test(entry.commit ?? '')) throw new Error(`Git source ${spec} needs "commit": a full 40-character SHA`);
  const url = /^[\w.-]+\/[\w.-]+$/.test(spec) ? `https://github.com/${spec}.git` : spec;
  const slug = spec.replace(/^[a-z]+:\/\//, '').replace(/\.git$/, '').replace(/[^\w.-]+/g, '__');
  const directory = join(cacheRoot, `${slug}-${entry.commit.slice(0, 12)}`);
  const head = () => spawnSync('git', ['-C', directory, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).stdout.trim();
  if (existsSync(directory) && head() === entry.commit) return directory;
  rmSync(directory, { recursive: true, force: true });
  mkdirSync(directory, { recursive: true });
  const git = (...args) => {
    const result = spawnSync('git', ['-C', directory, ...args], { encoding: 'utf8' });
    if (result.status !== 0) throw new Error(`git ${args.join(' ')} failed for ${spec}: ${result.stderr.trim()}`);
  };
  log(`Fetching ${spec} at ${entry.commit}`);
  git('init', '--quiet');
  git('fetch', '--quiet', '--depth', '1', url, entry.commit);
  git('-c', 'advice.detachedHead=false', 'checkout', '--quiet', 'FETCH_HEAD');
  if (head() !== entry.commit) throw new Error(`Checked out ${spec} does not match ${entry.commit}`);
  return directory;
}

// Returns [{ name, path, label, root }] in source order; throws on clashes.
export function resolveSkills(sourcesFile, { home, cacheRoot, log = () => {} }) {
  const base = sourcesFile ? dirname(resolve(sourcesFile)) : repository;
  const entries = sourcesFile ? JSON.parse(readFileSync(sourcesFile, 'utf8')) : [{ source: 'self' }];
  if (!Array.isArray(entries)) throw new Error('The sources file must hold a JSON list');
  const chosen = new Map();
  const roots = [];
  for (const entry of entries) {
    let root;
    let label;
    if (entry.source === 'self') {
      root = join(repository, 'skills');
      label = 'skills (this repository)';
    } else if (typeof entry.path === 'string') {
      const expanded = expandHome(entry.path, home);
      root = isAbsolute(expanded) ? expanded : resolve(base, expanded);
      label = entry.path;
    } else if (entry.git) {
      root = join(checkoutGit(entry, cacheRoot, log), entry.subdir ?? 'skills');
      label = `${entry.git}@${entry.commit.slice(0, 12)}`;
    } else {
      throw new Error(`Unrecognized source entry: ${JSON.stringify(entry)}`);
    }
    if (!existsSync(root) || !statSync(root).isDirectory()) throw new Error(`Skill source not found: ${root}`);
    roots.push(root);
    const available = skillNames(root);
    const wanted = entry.skills ?? available;
    const rename = entry.rename ?? {};
    for (const name of wanted) {
      if (!available.includes(name)) throw new Error(`Skill ${name} not found in ${label}`);
      if ((entry.exclude ?? []).includes(name)) continue;
      const installed = rename[name] ?? name;
      if (!NAME.test(installed)) throw new Error(`Invalid skill name: ${installed}`);
      const previous = chosen.get(installed);
      if (previous) {
        throw new Error(`Skill name clash: ${installed} comes from ${previous.label} and ${label}; exclude or rename one`);
      }
      chosen.set(installed, { name: installed, path: join(root, name), label, root });
    }
  }
  return { skills: [...chosen.values()], roots };
}

class Installer {
  constructor({ home, dryRun, managedRoots }) {
    this.home = home;
    this.dryRun = dryRun;
    // Raw and resolved forms, so a link written through a symlinked path still matches.
    this.managed = [...new Set(managedRoots.flatMap((root) => [resolve(root), realOrSelf(root)]))];
    this.status = 0;
  }

  log(message) { console.log(message); }
  conflict(message) { console.error(`Conflict: ${message}`); this.status = 1; }

  isManagedLink(path) {
    let target;
    try { target = readlinkSync(path); } catch { return false; }
    const absolute = resolve(dirname(path), target);
    return this.managed.some((root) => within(absolute, root) || within(realOrSelf(absolute), root));
  }

  act(message, action) {
    this.log(`${this.dryRun ? 'Would ' + message[0].toLowerCase() + message.slice(1) : message}`);
    if (!this.dryRun) action();
  }

  link(source, target) {
    let stat;
    try { stat = lstatSync(target); } catch { /* absent */ }
    if (stat?.isSymbolicLink()) {
      if (resolve(dirname(target), readlinkSync(target)) === source) return;
      if (this.isManagedLink(target) || !existsSync(target)) {
        this.act(`Relinked ${target} -> ${source}`, () => { unlinkSync(target); symlinkSync(source, target); });
        return;
      }
    }
    if (stat) { this.conflict(`${target} already exists; it was not replaced.`); return; }
    this.act(`Linked ${target} -> ${source}`, () => { mkdirSync(dirname(target), { recursive: true }); symlinkSync(source, target); });
  }

  // Links every entry of `wanted` (name -> source) into `directory` and removes
  // managed links there that are no longer wanted. Unmanaged entries are kept.
  sync(directory, wanted) {
    if (existsSync(directory)) {
      for (const name of readdirSync(directory)) {
        const path = join(directory, name);
        if (!lstatSync(path).isSymbolicLink() || wanted.has(name) || !this.isManagedLink(path)) continue;
        this.act(`Pruned ${path}`, () => unlinkSync(path));
      }
    }
    for (const [name, source] of wanted) this.link(source, join(directory, name));
  }

  writeRules(content, target) {
    let stat;
    try { stat = lstatSync(target); } catch { /* absent */ }
    if (stat?.isSymbolicLink() && !this.isManagedLink(target) && existsSync(target)) {
      this.conflict(`${target} is a link this installer does not manage; it was not replaced.`);
      return;
    }
    if (stat && !stat.isSymbolicLink()) {
      const current = readFileSync(target, 'utf8');
      if (!current.startsWith(RULES_HEADER)) {
        this.conflict(`${target} was not generated by this installer; it was not replaced.`);
        return;
      }
      if (current === content) return;
    }
    this.act(`Wrote ${target}`, () => {
      mkdirSync(dirname(target), { recursive: true });
      const temporary = `${target}.${process.pid}.tmp`;
      writeFileSync(temporary, content, { mode: 0o644 });
      if (stat?.isSymbolicLink()) unlinkSync(target);
      renameSync(temporary, target);
    });
  }

  mergeHooks(installer, template, target) {
    if (this.dryRun) { this.log(`Would merge ${template} into ${target}`); return; }
    const result = spawnSync(process.execPath, [installer, template, target], { encoding: 'utf8' });
    if (result.stdout.trim()) this.log(result.stdout.trim());
    if (result.status !== 0) { console.error(result.stderr.trim()); this.status = 1; }
  }
}

export function rulesContent(overlayPath) {
  const sources = ['rules/AGENTS.md', ...(overlayPath ? [overlayPath] : [])];
  let content = `${RULES_HEADER} Sources: ${sources.join(', ')}.\n     Edit those files and rerun the installer; changes made here are overwritten. -->\n\n`;
  content += readFileSync(join(repository, 'rules/AGENTS.md'), 'utf8').trimEnd() + '\n';
  if (overlayPath) content += '\n' + readFileSync(overlayPath, 'utf8').trimEnd() + '\n';
  return content;
}

export function main(argv = process.argv.slice(2), env = process.env) {
  let options;
  try { options = parseArgs(argv); } catch (error) {
    if (!(error instanceof UsageError)) throw error;
    console.error(`${error.message}\n\n${usage}`);
    return 2;
  }
  if (options.help) { console.log(usage); return 0; }

  const home = env.HOME || homedir();
  const codexHome = env.CODEX_HOME || join(home, '.codex');
  const cacheRoot = join(env.XDG_CACHE_HOME || join(home, '.cache'), 'agent-skills');
  const overlay = options.overlay ? resolve(expandHome(options.overlay, home)) : null;
  if (overlay && !existsSync(overlay)) { console.error(`Rules overlay not found: ${overlay}`); return 1; }

  let resolved;
  try {
    resolved = resolveSkills(options.sources && expandHome(options.sources, home), { home, cacheRoot, log: (m) => console.log(m) });
  } catch (error) {
    console.error(error.message);
    return 1;
  }

  const pruneRoots = options.pruneRoots.map((root) => resolve(expandHome(root, home)));
  const installer = new Installer({
    home,
    dryRun: options.dryRun,
    managedRoots: [repository, ...resolved.roots, cacheRoot, ...pruneRoots],
  });
  const skills = new Map(resolved.skills.map((skill) => [skill.name, skill.path]));
  const rules = rulesContent(overlay);

  installer.link(join(repository, 'scripts/agent-scratch.sh'), join(home, '.local/bin/agent-scratch'));

  if (options.claude) {
    const claude = join(home, '.claude');
    installer.sync(join(claude, 'skills'), skills);
    const hooks = new Map(readdirSync(join(repository, 'hooks/claude'))
      .filter((name) => name.endsWith('.sh'))
      .map((name) => [name, join(repository, 'hooks/claude', name)]));
    installer.sync(join(claude, 'hooks'), hooks);
    installer.mergeHooks(join(repository, 'hooks/claude/install-hooks.mjs'), join(repository, 'hooks/claude/hooks.json'), join(claude, 'settings.json'));
    installer.link(join(repository, 'integrations/claude/statusline-command.sh'), join(claude, 'statusline-command.sh'));
    installer.writeRules(rules, join(claude, 'CLAUDE.md'));
  }
  if (options.agents || options.codex) {
    installer.sync(join(home, '.agents/skills'), skills);
    installer.writeRules(rules, join(codexHome, 'AGENTS.md'));
    installer.writeRules(rules, join(home, '.config/opencode/AGENTS.md'));
  }
  if (options.codex) {
    if (spawnSync('codex', ['--version']).status === 0) {
      installer.sync(join(codexHome, 'hooks'), new Map([['auto-lint.mjs', join(repository, 'hooks/codex/auto-lint.mjs')]]));
      installer.mergeHooks(join(repository, 'hooks/codex/install-hooks.mjs'), join(repository, 'hooks/codex/hooks.json'), join(codexHome, 'hooks.json'));
    } else {
      console.error('Codex is not installed; its lint hook was skipped.');
      if (options.explicitCodex) installer.status = 1;
    }
  }
  return installer.status;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  process.exitCode = main();
}
